#!/usr/bin/env bash
# sg13g2-dll :: export the xschem schematics under design/ to SPICE.
#
#   design/netlist.sh                 # regenerate design/netlist/*.spice
#   design/netlist.sh --check         # regenerate to a temp dir and diff; non-zero if stale
#   design/netlist.sh --top <block>   # restrict to one top
#
# The single exporter for every block of this design (issue #24's PFD/charge
# pump/bias/filter and issue #23's delay cell, tap buffer and delay line).
# Each top is netlisted with its full hierarchy into one self-contained,
# includable file (`klt netlist --block`) under design/netlist/. xschem is only
# ever run through `klt netlist`, which forces the headless flags and kills a
# hung run; never call xschem directly.
#
# --check is the staleness gate: a schematic edited without re-export, or a
# committed netlist edited by hand, makes it exit 3. The `** sch_path:` stamps
# xschem writes are absolute; they are rewritten to repo-relative form so the
# committed bytes do not depend on which checkout produced them.
#
# Needs: klt, xschem (via klt), the SG13G2 PDK (PDK_ROOT, see sim/harness/env.sh).
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "${HERE}/.." && pwd)"
OUT_DIR="${HERE}/netlist"

# Tops and the .subckt set each export must contain (connectivity guard: a
# hierarchy that silently lost a branch fails the run).
BLOCKS=(pfd cp cp_bias loop_filter delay_cell tap_buffer delay_line)
expected_subckts() {
  case "$1" in
    pfd)         echo "pfd edgedet srlatch nand2_lv inv_lv inv2x_lv" ;;
    cp)          echo "cp cp_leg_p cp_leg_n cp_dumpbuf inv_lv" ;;
    cp_bias)     echo "cp_bias" ;;
    loop_filter) echo "loop_filter" ;;
    delay_cell)  echo "delay_cell" ;;
    tap_buffer)  echo "tap_buffer" ;;
    delay_line)  echo "delay_line delay_cell tap_buffer" ;;
    *)           echo "" ;;
  esac
}

CHECK=0
TOP=""
while [ $# -gt 0 ]; do
  case "$1" in
    --check) CHECK=1; shift ;;
    --top)   TOP="${2:-}"; [ -n "${TOP}" ] || { echo "netlist.sh: --top needs a block" >&2; exit 2; }; shift 2 ;;
    -h|--help) sed -n '2,20p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit 0 ;;
    *) echo "netlist.sh: unknown argument '$1'" >&2; exit 2 ;;
  esac
done

# shellcheck source=/dev/null
source "${ROOT}/sim/harness/env.sh" 2>/dev/null || true
command -v klt >/dev/null || { echo "netlist.sh: klt not on PATH" >&2; exit 1; }
[[ -n "${PDK_ROOT:-}" ]] || { echo "netlist.sh: no SG13G2 PDK found (set PDK_ROOT)" >&2; exit 1; }

if [[ -n "${TOP}" ]]; then
  case " ${BLOCKS[*]} " in *" ${TOP} "*) BLOCKS=("${TOP}") ;; *) echo "netlist.sh: unknown block '${TOP}'" >&2; exit 2 ;; esac
fi

TMP="$(mktemp -d /tmp/sg13g2-dll-netlist.XXXXXX)"
trap 'rm -rf "${TMP}"' EXIT

export_block() {
  local blk="$1" cell raw out
  raw="${TMP}/${blk}.raw"; out="${TMP}/${blk}.spice"
  klt netlist "${HERE}/${blk}.sch" -o "${raw}" --block --rcfile "${HERE}/xschemrc" >/dev/null
  for cell in $(expected_subckts "${blk}"); do
    grep -qiE "^\.subckt +${cell}( |$)" "${raw}" \
      || { echo "netlist.sh: .subckt ${cell} missing from the ${blk} export" >&2; return 1; }
  done
  if grep -qE '^\.subckt .*\bnet[0-9]+\b' "${raw}" || grep -q 'IS MISSING' "${raw}"; then
    echo "netlist.sh: ${blk}: unresolved label or unconnected pin in the export" >&2; return 1
  fi
  {
    echo "* sg13g2-dll :: ${blk} -- generated by design/netlist.sh from design/${blk}.sch"
    echo "* do not edit by hand; regenerate with design/netlist.sh"
    sed -E "s#^(\*\* (sch|sym)_path: ).*/design/#\1design/#" "${raw}"
  } > "${out}"
}

rc=0
for blk in "${BLOCKS[@]}"; do
  export_block "${blk}" || { rc=1; continue; }
  if [[ ${CHECK} -eq 1 ]]; then
    if ! diff -u "${OUT_DIR}/${blk}.spice" "${TMP}/${blk}.spice" > "${TMP}/${blk}.diff" 2>&1; then
      echo "netlist.sh: STALE design/netlist/${blk}.spice (re-run design/netlist.sh)" >&2
      head -20 "${TMP}/${blk}.diff" >&2
      rc=3
    else
      echo "netlist.sh: ok ${blk}" >&2
    fi
  else
    mkdir -p "${OUT_DIR}"
    cp "${TMP}/${blk}.spice" "${OUT_DIR}/${blk}.spice"
    echo "netlist.sh: wrote design/netlist/${blk}.spice" >&2
  fi
done
exit ${rc}
